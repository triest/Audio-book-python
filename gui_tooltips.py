"""Всплывающие подсказки и справка по словарям ударений (вкладки «Словарь ударений» и «Проверка ударений»).

`apply_tips(root, {текст кнопки: подсказка})` обходит дерево виджетов и вешает подсказку на каждый виджет, чей `text`
совпадает с ключом (так не нужно хранить ссылки на все кнопки). `add_help_button(parent)` — кнопка «? Какой словарь за что»
с окном-справкой (`HELP_TEXT`). `tip_headings` — подсказки на заголовки столбцов Treeview, `tip_tabs` — на ярлыки Notebook.
"""
from __future__ import annotations

import tkinter as tk
from tkinter import ttk


def _popup(owner, x, y, text, wrap=420):
    tw = tk.Toplevel(owner)
    tw.wm_overrideredirect(True)
    tw.wm_geometry(f"+{x}+{y}")
    tk.Label(tw, text=text, justify="left", wraplength=wrap, background="#ffffe1", foreground="#000",
             relief="solid", borderwidth=1, padx=6, pady=4).pack()
    return tw


class Tooltip:
    def __init__(self, widget, text: str, delay: int = 500):
        self.widget, self.text, self.delay = widget, text, delay
        self._tip = None
        self._job = None
        widget.bind("<Enter>", self._schedule, add="+")
        widget.bind("<Leave>", self._hide, add="+")
        widget.bind("<ButtonPress>", self._hide, add="+")

    def _schedule(self, _e=None):
        self._cancel()
        self._job = self.widget.after(self.delay, self._show)

    def _cancel(self):
        if self._job:
            try:
                self.widget.after_cancel(self._job)
            except Exception:
                pass
            self._job = None

    def _show(self):
        if self._tip or not self.text:
            return
        self._tip = _popup(self.widget, self.widget.winfo_rootx() + 12,
                           self.widget.winfo_rooty() + self.widget.winfo_height() + 4, self.text)

    def _hide(self, _e=None):
        self._cancel()
        if self._tip:
            self._tip.destroy()
            self._tip = None


def add_tip(widget, text: str):
    Tooltip(widget, text)


def apply_tips(root, tips: dict):
    """Подсказки по тексту виджета (кнопки, флажки, переключатели, рамки)."""
    def walk(w):
        try:
            t = str(w.cget("text"))
        except Exception:
            t = None
        if t and t in tips:
            add_tip(w, tips[t])
        for c in w.winfo_children():
            walk(c)
    walk(root)


def _hover_region(widget, key_of, tips):
    state = {"tw": None, "key": None}

    def hide(_e=None):
        if state["tw"]:
            state["tw"].destroy()
            state["tw"] = None
        state["key"] = None

    def motion(e):
        key = key_of(e)
        if key == state["key"]:
            return
        hide()
        text = tips.get(key) if key is not None else None
        if text:
            state["key"] = key
            state["tw"] = _popup(widget, e.x_root + 10, e.y_root + 18, text, 380)

    widget.bind("<Motion>", motion, add="+")
    widget.bind("<Leave>", hide, add="+")
    widget.bind("<ButtonPress>", hide, add="+")


def tip_headings(tree, tips: dict):
    """Подсказка на заголовок столбца Treeview (ключ — имя столбца)."""
    def key_of(e):
        if tree.identify_region(e.x, e.y) != "heading":
            return None
        idx = int(tree.identify_column(e.x)[1:]) - 1
        cols = tree["columns"]
        return cols[idx] if 0 <= idx < len(cols) else None
    _hover_region(tree, key_of, tips)


def tip_tabs(nb, tips: dict):
    """Подсказка на ярлык вкладки Notebook (ключ — текст ярлыка)."""
    def key_of(e):
        try:
            idx = nb.index(f"@{e.x},{e.y}")
        except tk.TclError:
            return None
        return nb.tab(idx, "text")
    _hover_region(nb, key_of, tips)


