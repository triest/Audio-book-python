def show_help(parent):
    win = tk.Toplevel(parent)
    win.title("Словари ударений: что за что отвечает")
    win.geometry("820x640")
    txt = tk.Text(win, wrap="word", padx=10, pady=8, font=("TkDefaultFont", 10))
    sb = ttk.Scrollbar(win, command=txt.yview)
    txt.configure(yscrollcommand=sb.set)
    sb.pack(side="right", fill="y")
    txt.pack(fill="both", expand=True)
    txt.insert("1.0", HELP_TEXT)
    txt.configure(state="disabled")


def add_help_button(parent, **pack):
    b = ttk.Button(parent, text="? Какой словарь за что", command=lambda: show_help(parent.winfo_toplevel()))
    b.pack(**(pack or {"side": "right", "padx": 6}))
    add_tip(b, "Справка: чем различаются forced_stress_words.json, файл правок книги, manual_stress_overrides.json, "
               "подмены произношения и «подтверждения»; что такое омографы; чем отличаются вкладки.")
    return b


